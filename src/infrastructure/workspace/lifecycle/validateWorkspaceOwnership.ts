import { existsSync, lstatSync, readdirSync, rmdirSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';
import type { WorkspaceFacts } from '../WorkspaceFacts.js';
import type { WorkspaceOptions } from '../WorkspaceOptions.js';
import { discoverGitWorktrees } from './discoverGitWorktrees.js';
import { isInside, runGit } from './workspaceState.js';
import type { GitWorktree, RegisteredWorkspace } from './workspaceState.js';

const generatedMetadata = new Set([
  '.serena/.gitignore',
  '.serena/project.yml',
  '.serena/project.local.yml',
]);

function hasKnownMetadataNames(names: string[]): boolean {
  const knownNames = ['.gitignore', 'project.yml', 'project.local.yml', 'memories'];
  return names.every((name) => knownNames.includes(name));
}

function areSafeMetadataEntries(directory: string, names: string[]): boolean {
  for (const name of names) {
    const path = resolve(directory, name);
    const info = lstatSync(path);
    if (
      name === 'memories' &&
      (!info.isDirectory() || info.isSymbolicLink() || readdirSync(path).length !== 0)
    )
      return false;
    if (name !== 'memories' && (!info.isFile() || info.isSymbolicLink())) return false;
  }
  return true;
}

/** Confirm the live branch, head, base ancestry, and registered target all agree. */
export function isExactWorkspace(root: string, entry: RegisteredWorkspace): boolean {
  const live = discoverGitWorktrees(root).find(
    (worktree) => resolve(worktree.path) === resolve(entry.executionRoot),
  );
  if (!live || live.branch !== entry.branch || live.head !== entry.headSha) return false;
  try {
    return (
      runGit(['rev-parse', `${entry.branch}^{commit}`], root) === entry.headSha &&
      runGit(['merge-base', '--is-ancestor', entry.baseSha, entry.headSha], root) === ''
    );
  } catch {
    return false;
  }
}

/** Match persisted location and ownership facts before registered cleanup. */
export function matchesWorkspaceFacts(
  entry: RegisteredWorkspace,
  facts: WorkspaceFacts,
  root: string,
): boolean {
  return (
    Boolean(entry?.ownership) &&
    entry.repositoryRoot === root &&
    entry.executionRoot === facts.executionRoot &&
    entry.branch === facts.branch &&
    entry.baseSha === facts.baseSha &&
    entry.ownership.runId === facts.ownership.runId &&
    entry.ownership.issue === facts.ownership.issue &&
    entry.ownership.protocol === facts.ownership.protocol
  );
}

/** Recognize only the known, untracked Serena files generated by Sloop tooling. */
export function generatedSerenaPaths(entry: RegisteredWorkspace): string[] | undefined {
  const status = runGit(['status', '--porcelain=v1', '--untracked-files=all'], entry.executionRoot);
  const statusLines = status ? status.split(/\r?\n/) : [];
  if (!statusLines.every((line) => line.startsWith('?? ') && generatedMetadata.has(line.slice(3))))
    return undefined;
  const directory = resolve(entry.executionRoot, '.serena');
  try {
    const directoryInfo = lstatSync(directory);
    if (!directoryInfo.isDirectory() || directoryInfo.isSymbolicLink()) return undefined;
    const names = readdirSync(directory).sort();
    const expectedPaths = names.map((name) => `.serena/${name}`);
    if (
      !hasKnownMetadataNames(names) ||
      statusLines.some((line) => !expectedPaths.includes(line.slice(3)))
    )
      return undefined;
    if (!areSafeMetadataEntries(directory, names)) return undefined;
  } catch {
    return statusLines.length === 0 && !existsSync(directory) ? [] : undefined;
  }
  return readdirSync(directory).map((name) => `.serena/${name}`);
}

/** Remove recognized generated metadata only after the full shape is verified. */
export function removeGeneratedSerenaMetadata(entry: RegisteredWorkspace): boolean {
  const paths = generatedSerenaPaths(entry);
  if (paths === undefined) return false;
  if (!paths.length) return true;
  for (const path of paths) {
    if (path === '.serena/memories') rmdirSync(resolve(entry.executionRoot, path));
    else unlinkSync(resolve(entry.executionRoot, path));
  }
  rmdirSync(resolve(entry.executionRoot, '.serena'));
  return true;
}

/** Validate registration ownership and strict worktree containment for recovery. */
export function matchesRecoveryOwnership(
  entry: RegisteredWorkspace,
  options: WorkspaceOptions,
  root: string,
): boolean {
  return (
    Boolean(entry?.ownership) &&
    entry.repositoryRoot === root &&
    entry.workspaceRoot === root &&
    entry.ownership.issue === options.issue &&
    entry.ownership.protocol === 'sloop-workspace-v1' &&
    (entry.ownership.runId === options.runId ||
      (options.branch !== undefined && entry.branch === options.branch)) &&
    (options.branch === undefined || entry.branch === options.branch) &&
    isInside(resolve(root, options.worktreeRoot ?? '.sloop/worktrees'), entry.executionRoot)
  );
}

/** Match a live worktree against the exact persisted path, branch, and head. */
export function matchesLiveWorkspace(live: GitWorktree, facts: WorkspaceFacts): boolean {
  return (
    resolve(live.path) === resolve(facts.executionRoot) &&
    live.branch === facts.branch &&
    live.head === facts.headSha
  );
}
